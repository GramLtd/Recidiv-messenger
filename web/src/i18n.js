const IDX = { en: 0, uk: 1, be: 2 };

const KEY = 'recidivist.lang';
const initial = (() => {
  try {
    return localStorage.getItem(KEY) || 'ru';
  } catch {
    return 'ru';
  }
})();

export const useLang = create((set) => ({
  lang: initial,
  setLang(lang) {
    try { localStorage.setItem(KEY, lang); } catch {}
    document.documentElement.lang = lang;
    set({ lang });
  },
}));

export function translate(lang, s) {
  if (lang === 'ru' || !(lang in IDX)) return s;
  return D[s]?.[IDX[lang]] || s;
}
export const t = (s) => translate(useLang.getState().lang, s);
/** Hook: re-renders the component when the language changes. */
export function useT() {
  const lang = useLang((s) => s.lang);
  return (s) => translate(lang, s);
}
